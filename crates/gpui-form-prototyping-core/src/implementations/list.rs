//! Milestone M3 (backlog #3): prototyping generator for
//! `component(list(item = ...))` fields.
//!
//! v1 renders repeatable rows over `current_data.<field>_items()` with a
//! Remove button per row and one Add button appending a default item,
//! wired to the holder's generated `add_<field>` / `remove_<field>`
//! operations. Per-row input entities (and their index-shifted
//! subscriptions) stay application-authored in v1 — R17's conservative-first
//! mitigation — so rows display their current value and mutate through the
//! buttons. i18n keys stay index-free (hazard 11): the group label, the
//! per-row label, and the add/remove buttons resolve
//! `{form}.{field}_label` / `{form}.{field}_item_label` /
//! `{form}.{field}_add` / `{form}.{field}_remove`.

use gpui_form_schema::registry::{FieldVariant, GpuiFormShape};
use proc_macro2::TokenStream;
use quote::{format_ident, quote};
use syn::Type;

use crate::imports::ImportItem;

use super::{FieldCodeGenerator, ResolvedField};

pub struct ListCodeGenerator;

const IMPORTS: &[ImportItem] = &[
    ImportItem::path("::gpui_kit::component::button::Button"),
    ImportItem::path("::gpui_kit::component::h_flex"),
];

impl FieldCodeGenerator for ListCodeGenerator {
    fn generate_imports(&self, _field: &FieldVariant) -> Vec<ImportItem> {
        IMPORTS.to_vec()
    }

    fn generate_cx_new_call(
        &self,
        _field: &ResolvedField<'_>,
        _component: &GpuiFormShape,
    ) -> Option<TokenStream> {
        // No per-item entities in v1 (R17): the holder owns the data, rows
        // render from `<field>_items()`.
        None
    }

    fn generate_field_initializers(
        &self,
        _field: &ResolvedField<'_>,
        _component: &GpuiFormShape,
    ) -> Option<TokenStream> {
        None
    }

    fn generate_impl_members(
        &self,
        field: &ResolvedField<'_>,
        component: &GpuiFormShape,
    ) -> Vec<TokenStream> {
        let control_ident = format_ident!("{}_list_control", field.field_name());
        let field_name_str = field.field_name();
        let items_fn = format_ident!("{}_items", field_name_str);
        let add_fn = format_ident!("add_{}", field_name_str);
        let remove_fn = format_ident!("remove_{}", field_name_str);
        let row_button_prefix = format!("{field_name_str}-remove");
        let add_button_id = format!("{field_name_str}-add");
        let item_type = list_item_type(field);
        let group_label = super::generate_label_tokens(field, component);
        let item_label = super::localized_text_tokens(field, component, "item_label");
        let add_label = match add_label_override(field) {
            Some(label) => quote! { #label.to_string() },
            None => super::localized_text_tokens(field, component, "add"),
        };
        let remove_label = super::localized_text_tokens(field, component, "remove");

        vec![quote! {
            /// Repeatable-row control for this list field: one row per
            /// current item (Remove button each) plus an Add button
            /// appending a default item. Generated by the prototyping
            /// scaffold (milestone M3); edit freely — it is app-owned code.
            fn #control_ident(&self, cx: &mut Context<Self>) -> impl IntoElement {
                let mut rows = ::std::vec::Vec::new();
                for (index, item) in self.current_data.#items_fn().iter().enumerate() {
                    let remove_id = format!("{}-{}", #row_button_prefix, index);
                    rows.push(
                        h_flex()
                            .justify_between()
                            .child(
                                field()
                                    .label(format!("{} {}", #item_label, index + 1))
                                    .child(format!("{:?}", item)),
                            )
                            .child(
                                Button::new(remove_id)
                                    .label(#remove_label.clone())
                                    .on_click(cx.listener(move |this, _, _, cx| {
                                        this.current_data.#remove_fn(index);
                                        cx.notify();
                                    })),
                            ),
                    );
                }
                v_flex()
                    .gap_2()
                    .child(field().label(#group_label.clone()))
                    .children(rows)
                    .child(
                        Button::new(#add_button_id)
                            .label(#add_label.clone())
                            .on_click(cx.listener(|this, _, _, cx| {
                                this.current_data.#add_fn(
                                    <#item_type as ::core::default::Default>::default(),
                                );
                                cx.notify();
                            })),
                    )
            }
        }]
    }

    fn generate_render_child(
        &self,
        field: &ResolvedField<'_>,
        _component: &GpuiFormShape,
    ) -> TokenStream {
        let control_ident = format_ident!("{}_list_control", field.field_name());
        quote! {
            .child(self.#control_ident(cx))
        }
    }

    fn generate_focusable_cycle(
        &self,
        _field: &ResolvedField<'_>,
        _component: &GpuiFormShape,
    ) -> Option<TokenStream> {
        None
    }

    fn generate_subscription(
        &self,
        _field: &ResolvedField<'_>,
        _component: &GpuiFormShape,
    ) -> Option<super::GeneratedSubscription> {
        // v1 rows have no per-item entities to subscribe to ([D5]/R17).
        None
    }
}

/// The scalar item type: the inner `T` of the field's `Vec<T>` metadata.
fn list_item_type(field: &ResolvedField<'_>) -> Type {
    let value_type = field.value_type();
    let Type::Path(type_path) = value_type else {
        return syn::parse_quote!(::core::ffi::c_void);
    };
    let last_segment = type_path.path.segments.last();
    if let Some(segment) = last_segment
        && segment.ident == "Vec"
        && let syn::PathArguments::AngleBracketed(args) = &segment.arguments
        && let Some(syn::GenericArgument::Type(inner)) = args.args.first()
    {
        return inner.clone();
    }
    syn::parse_quote!(::core::ffi::c_void)
}

/// The optional `add_label = "..."` override parsed by the derive — surfaced
/// through the behaviour metadata? v1 keeps it derive-side only; the button
/// falls back to the localized key.
fn add_label_override(_field: &ResolvedField<'_>) -> Option<String> {
    None
}
